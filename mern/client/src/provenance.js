/**
 * What every displayed value actually is, and where it came from.
 *
 * Two independent questions, and the UI must answer both because neither
 * answers the other:
 *
 *   1. KIND  - is this number a sensor reading, arithmetic on sensor readings,
 *              or the output of a hand-tuned model?
 *   2. ORIGIN - is the underlying data from physical hardware, a research
 *              dataset, or a synthetic simulation?
 *
 * A `MEASURED` field on `SIMULATED` data is not a measurement of anything. That
 * is precisely why both labels are shown: tagging voltage as MEASURED while the
 * fleet is synthetic would be the more misleading of the two half-truths, and
 * this project already shipped a dashboard that implied validation it did not
 * have (see docs/architecture_diagram_spec.md).
 *
 * This file is the single source of truth. A component that displays a value
 * without a matching entry here should fail the lookup loudly rather than
 * render an unlabelled number - see `describe`.
 */

