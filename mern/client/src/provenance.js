/** Look up a field, or return a loud placeholder rather than an unlabelled number. */
export function describe(field) {
  const entry = FIELDS[field];
  if (entry) return entry;
  return {
    kind: 'UNCLASSIFIED',
    label: field,
    unit: '',
    definition:
      'This field has no provenance entry. Add one in client/src/provenance.js ' +
      'before displaying it — an unlabelled number is the thing this module exists to prevent.',
  };
}

export function kindTone(kind) {
  if (kind === KIND.MEASURED) return 'measured';
  if (kind === KIND.CALCULATED) return 'calculated';
  if (kind === KIND.MODEL) return 'model';
  return 'unclassified';
}
